#ifndef AIG_EVENT_H
#define AIG_EVENT_H
#include <pthread.h>
#include <stdio.h>

/* One normalized thing an actor did to the repo. Producers: transcript.c (M1),
 * the filesystem watcher (M2). Consumer: model.c. */
typedef enum {
    EV_TURN,   /* a new prompt started a turn; text = prompt */
    EV_READ,   /* Read of a file */
    EV_SEARCH, /* Grep/Glob under path; text = pattern */
    EV_CREATE, /* file created */
    EV_EDIT,   /* file changed with known diff size */
    EV_DELETE, /* file removed */
    EV_TOUCH,  /* file changed, diff unknown (e.g. generated by a command) */
    EV_BASH,   /* command started; text = command */
    EV_KIND_COUNT
} EvKind;

typedef struct {
    double ts;
    unsigned long seq; /* ingest order; breaks ts ties */
    EvKind kind;
    char *actor;      /* stable actor id (session or subagent id) */
    char *actor_name; /* display name */
    char *path;       /* repo-relative ("" = repo root); NULL for TURN/BASH */
    char *text;
    int add, del;     /* diff lines */
    int lines;        /* file length after the event, -1 = unknown */
    int turn;
} Event;

const char *ev_kind_name(EvKind k);
void ev_free(Event *e);
int ev_cmp(const void *a, const void *b); /* by ts, then seq */
void ev_print_json(FILE *f, const Event *e);

/* Mutex-guarded MPSC queue: ingest thread pushes, render thread drains. */
typedef struct {
    pthread_mutex_t mu;
    Event *items;
    size_t n, cap;
} EvQueue;

void evq_init(EvQueue *q);
void evq_push(EvQueue *q, Event e); /* takes ownership of e's strings */
/* Moves all queued events into *out (caller frees each and the array). */
size_t evq_drain(EvQueue *q, Event **out);

#endif
