-- aic: commands and <Plug> mappings only; everything else loads lazily.
if vim.g.loaded_aic then
  return
end
vim.g.loaded_aic = 1

local function aic()
  return require('aic')
end

local cmd = vim.api.nvim_create_user_command
cmd('Aic', function()
  aic().open()
end, { desc = 'aic: show the last aic view in this window' })
cmd('AicToggle', function()
  aic().toggle()
end, { desc = 'aic: toggle between the code and the last aic view' })
cmd('AicHistory', function()
  aic().show('trace')
end, { desc = 'aic: show the history (trace) in this window' })
cmd('AicQuestions', function()
  aic().show('questions')
end, { desc = 'aic: show the questions (chat) in this window' })
cmd('AicDocs', function()
  aic().docs()
end, { desc = 'aic: pick a doc (or make a new one)' })
local function doc_names(lead)
  return vim.tbl_filter(function(n)
    return n:sub(1, #lead) == lead
  end, require('aic.doc').names())
end
cmd('AicDoc', function(o)
  aic().doc(o.args)
end, { nargs = '?', complete = doc_names, desc = 'aic: show a doc (default: the current/last one)' })
cmd('AicPrompts', function()
  aic().prompts()
end, { desc = 'aic: edit or make a prompt template' })
cmd('AicDocNew', function(o)
  aic().doc_new(o.args)
end, { nargs = '?', desc = 'aic: new doc' })
cmd('AicSubmit', function(o)
  aic().submit({ range = o.range, line1 = o.line1, line2 = o.line2 })
end, { range = true, desc = 'aic: submit the doc (or range) through a prompt template, with preview' })
cmd('AicSubmitNow', function(o)
  aic().submit({ range = o.range, line1 = o.line1, line2 = o.line2, now = true })
end, { range = true, desc = 'aic: submit now (interrupts the running tool)' })
cmd('AicHold', function()
  aic().hold()
end, { desc = 'aic: hold the worker' })
cmd('AicContinue', function(o)
  aic().continue(o.args)
end, { nargs = '*', desc = 'aic: release hold [with message]' })
cmd('AicCompile', function()
  aic().compile()
end, { desc = 'aic: compile the current doc' })
cmd('AicFix', function(o)
  aic().fix({ range = o.range, line1 = o.line1, line2 = o.line2, reopen = o.bang })
end, { range = true, bang = true, desc = 'aic: the compiler proposes fixes to the doc (or range); ! shows the last ones' })
cmd('AicAsk', function()
  aic().ask()
end, { desc = 'aic: ask about the thing under the cursor' })
cmd('AicAskTemplate', function(o)
  aic().ask_template(o.args)
end, { nargs = '?', desc = 'aic: the compiler template for questions and ask-at-cursor (ask = default)' })
cmd('AicLastAnswer', function()
  require('aic.ask').reopen()
end, { desc = 'aic: reopen the last compiler answer' })
cmd('AicWhatIf', function()
  aic().whatif()
end, { desc = 'aic: what-if on the node under the cursor' })
cmd('AicChat', function(o)
  aic().chat(o.args)
end, { nargs = '+', desc = 'aic: send a chat message' })
cmd('AicBlame', function()
  aic().blame()
end, { desc = 'aic: show the trace event for this line' })
cmd('AicAttach', function()
  aic().attach()
end, { desc = 'aic: pick the worker session' })
cmd('AicDiagnostics', function()
  aic().diagnostics()
end, { desc = 'aic: load compile diagnostics into the quickfix list' })
cmd('AicNextUnseen', function()
  aic().next_unseen(1)
end, { desc = 'aic: jump to the next unseen trace node' })
cmd('AicPrevUnseen', function()
  aic().next_unseen(-1)
end, { desc = 'aic: jump to the previous unseen trace node' })
cmd('AicNextTouched', function()
  aic().next_touched(1)
end, { desc = 'aic: next touched range in this file' })
cmd('AicPrevTouched', function()
  aic().next_touched(-1)
end, { desc = 'aic: previous touched range in this file' })
cmd('AicRefresh', function()
  aic().refresh()
end, { desc = 'aic: re-resolve the session and reload files' })
cmd('AicUsage', function()
  aic().usage()
end, { desc = 'aic: context/cost usage, quota, compact' })
local function which(names)
  return function(lead)
    return vim.tbl_filter(function(n)
      return n:sub(1, #lead) == lead
    end, names)
  end
end
cmd('AicCompact', function(o)
  aic().compact(o.args, false)
end, { nargs = 1, complete = which({ 'compile', 'ask', 'worker' }), desc = 'aic: compact a session (compile|ask|worker)' })
cmd('AicReset', function(o)
  aic().compact(o.args, true)
end, { nargs = 1, complete = which({ 'compile', 'ask' }), desc = 'aic: reset a compiler session (compile|ask)' })

local map = vim.keymap.set
local function plug(name, rhs, modes)
  map(modes or 'n', '<Plug>(aic-' .. name .. ')', rhs, { silent = true })
end
plug('open', '<Cmd>Aic<CR>')
plug('toggle', '<Cmd>AicToggle<CR>')
plug('history', '<Cmd>AicHistory<CR>')
plug('questions', '<Cmd>AicQuestions<CR>')
plug('docs', '<Cmd>AicDocs<CR>')
plug('doc', '<Cmd>AicDoc<CR>')
plug('doc-new', '<Cmd>AicDocNew<CR>')
plug('prompts', '<Cmd>AicPrompts<CR>')
plug('submit', '<Cmd>AicSubmit<CR>')
plug('submit', ':AicSubmit<CR>', 'x')
plug('submit-now', '<Cmd>AicSubmitNow<CR>')
plug('submit-now', ':AicSubmitNow<CR>', 'x')
plug('hold', '<Cmd>AicHold<CR>')
plug('continue', '<Cmd>AicContinue<CR>')
plug('compile', '<Cmd>AicCompile<CR>')
plug('fix', '<Cmd>AicFix<CR>')
plug('fix', ':AicFix<CR>', 'x')
plug('ask', '<Cmd>AicAsk<CR>')
plug('whatif', '<Cmd>AicWhatIf<CR>')
plug('ask-template', '<Cmd>AicAskTemplate<CR>')
plug('last-answer', '<Cmd>AicLastAnswer<CR>')
plug('blame', '<Cmd>AicBlame<CR>')
plug('attach', '<Cmd>AicAttach<CR>')
plug('diagnostics', '<Cmd>AicDiagnostics<CR>')
plug('next-unseen', '<Cmd>AicNextUnseen<CR>')
plug('prev-unseen', '<Cmd>AicPrevUnseen<CR>')
plug('next-touched', '<Cmd>AicNextTouched<CR>')
plug('prev-touched', '<Cmd>AicPrevTouched<CR>')
plug('usage', '<Cmd>AicUsage<CR>')
plug('follow', function()
  aic().follow()
end)
